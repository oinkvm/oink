    /// 在一个独立的具名剪贴板上读写，不影响用户的系统剪贴板。
    #[test]
    fn round_trip_on_private_pasteboard() {
        let name = format!("com.hachiwii.oink.test.{}", std::process::id());
        let n = Some(name.as_str());
        let before = change_count(n);
        let png = tiny_png();
        let items = vec![
            ClipData::Html("<b>hi</b>".into()),
            ClipData::Rtf(b"{\\rtf1 hi}".to_vec()),
            ClipData::Png(png.clone()),
            ClipData::Text("hi\r\nthere".into()),
        ];
        let cc = write(n, &items, Sensitivity::Concealed).unwrap();
        assert!(cc > before);
        let snap = read(n).unwrap();
        assert_eq!(snap.change_count, cc);
        assert_eq!(snap.sensitivity, Sensitivity::Concealed);
        assert!(snap.items.contains(&ClipData::Html("<b>hi</b>".into())));
        assert!(snap.items.contains(&ClipData::Rtf(b"{\\rtf1 hi}".to_vec())));
        assert!(snap.items.contains(&ClipData::Png(png)));
        assert!(snap.items.contains(&ClipData::Text("hi\nthere".into())));

        write(n, &[ClipData::Text("x".into())], Sensitivity::AutoGenerated).unwrap();
        assert_eq!(read(n).unwrap().sensitivity, Sensitivity::AutoGenerated);
        write(n, &[ClipData::Text("x".into())], Sensitivity::Normal).unwrap();
        assert_eq!(read(n).unwrap().sensitivity, Sensitivity::Normal);
    }

