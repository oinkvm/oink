    #[test]
    fn custom_bytes_and_all_privacy_markers_round_trip() {
        let name = format!("com.hachiwii.oink.test.custom.{}", std::process::id());
        let mut items = vec![
            formats::custom(ClipPlatform::Mac, "example.application.binary", vec![0, 255, 7, 0]),
            formats::custom(ClipPlatform::Windows, "foreign.application", vec![9]),
            ClipData::Text("same".into()),
        ];
        for (i, marker) in formats::MAC_MARKERS.iter().enumerate() {
            items.push(formats::custom(ClipPlatform::Mac, marker, vec![i as u8, 0, 255]));
        }
        write(Some(&name), &items, Sensitivity::Transient).unwrap();
        let snap = read(Some(&name)).unwrap();
        assert_eq!(snap.sensitivity, Sensitivity::Transient);
        for item in items.iter().filter(|d| {
            !matches!(
                d,
                ClipData::Custom {
                    platform: ClipPlatform::Windows,
                    ..
                }
            )
        }) {
            assert!(snap.items.contains(item), "missing {item:?}");
        }
        assert!(!file_types_per_item(Some(&name))[0].contains(&"foreign.application".into()));
        write(Some(&name), &[ClipData::Text("same".into())], Sensitivity::Normal).unwrap();
        let snap = read(Some(&name)).unwrap();
        assert_eq!(snap.sensitivity, Sensitivity::Normal);
        assert!(
            !snap
                .items
                .iter()
                .any(|d| matches!(d, ClipData::Custom { name, .. } if formats::MAC_MARKERS.contains(&name.as_str())))
        );
    }

    /// 测试用的临时目录。
    struct Tmp(PathBuf);
    impl Tmp {
        fn new(tag: &str) -> Self {
            let p = std::env::temp_dir().join(format!("oink-pb-{tag}-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&p);
            std::fs::create_dir_all(&p).unwrap();
            Self(p)
        }
    }
    impl Drop for Tmp {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn file_types_per_item(n: Option<&str>) -> Vec<Vec<String>> {
        autoreleasepool(|_| {
            board(n)
                .pasteboardItems()
                .map(|items| {
                    items
                        .iter()
                        .map(|i| i.types().iter().map(|t| t.to_string()).collect())
                        .collect()
                })
                .unwrap_or_default()
        })
    }

    fn files_of(snap: &ClipSnapshot) -> Vec<crate::FileEntry> {
        snap.items
            .iter()
            .find_map(|i| match i {
                ClipData::Files(f) => Some(f.clone()),
                _ => None,
            })
            .expect("应读到文件清单")
    }

    /// 写入带 local_path 的文件清单（只写顶层 URL）→ 读回展开的清单；文本与隐私标记保留；
    /// 写入返回的 changeCount 就是读到的 changeCount（同步逻辑据此识别自己的写入）。
    #[test]
    fn files_round_trip_on_private_pasteboard() {
        let t = Tmp::new("files");
        let dir = t.0.join("Folder");
        std::fs::create_dir_all(dir.join("sub")).unwrap();
        std::fs::write(dir.join("sub/a.txt"), "aaa").unwrap();
        std::fs::write(dir.join("b.txt"), "b").unwrap();
        let file = t.0.join("single.txt");
        std::fs::write(&file, "12345").unwrap();
        let (list, _) = files::expand(&[dir.clone(), file.clone()]).unwrap();
        assert_eq!(list.len(), 5);

        let name = format!("com.hachiwii.oink.test.files.{}", std::process::id());
        let n = Some(name.as_str());
        let items = vec![
            ClipData::Files(list.clone()),
            ClipData::Text("Folder\rsingle.txt".into()),
        ];
        let cc = write(n, &items, Sensitivity::Concealed).unwrap();
        assert_eq!(change_count(n), cc, "写入只应让 changeCount 变化一次");

        // 每个顶层条目一个剪贴板条目；子条目不写。
        let per_item = file_types_per_item(n);
        assert_eq!(per_item.len(), 2);
        for types in &per_item {
            assert!(types.iter().any(|t| t == "public.file-url"));
            assert!(types.iter().any(|t| t == CONCEALED));
        }
        assert!(per_item[0].iter().any(|t| t == "public.utf8-plain-text"));

        let snap = read(n).unwrap();
        assert_eq!(snap.change_count, cc);
        assert_eq!(snap.sensitivity, Sensitivity::Concealed);
        let got = files_of(&snap);
        assert_eq!(got, list);
        assert!(snap.items.contains(&ClipData::Text("Folder\rsingle.txt".into())));
        // 读取不改变 changeCount。
        assert_eq!(change_count(n), cc);
    }

    /// Finder 写的是文件引用 URL（`file:///.file/id=…`），也要能解析；有文件时不把图标图片当作 PNG。
    #[test]
    fn file_reference_urls_resolve_and_icons_are_ignored() {
        let t = Tmp::new("fileref");
        let file = t.0.join("ref.txt");
        std::fs::write(&file, "r").unwrap();
        let name = format!("com.hachiwii.oink.test.fileref.{}", std::process::id());
        let n = Some(name.as_str());
        let reference = autoreleasepool(|_| {
            let url = NSURL::fileURLWithPath(&NSString::from_str(&file.to_string_lossy()));
            url.fileReferenceURL()
                .and_then(|u| u.absoluteString())
                .unwrap()
                .to_string()
        });
        assert!(reference.starts_with("file:///.file/id="), "{reference}");
        autoreleasepool(|_| {
            let rep = NSBitmapImageRep::imageRepWithData(&NSData::with_bytes(&tiny_png())).unwrap();
            let tiff = rep.TIFFRepresentation().unwrap();
            let pb = board(n);
            pb.clearContents();
            let item = NSPasteboardItem::new();
            // SAFETY: 读取 AppKit 导出的类型常量。
            unsafe {
                assert!(item.setString_forType(&NSString::from_str(&reference), NSPasteboardTypeFileURL));
                assert!(item.setData_forType(&tiff, NSPasteboardTypeTIFF));
            }
            let obj: Retained<ProtocolObject<dyn NSPasteboardWriting>> = ProtocolObject::from_retained(item);
            assert!(pb.writeObjects(&NSArray::from_retained_slice(&[obj])));
        });
        let snap = read(n).unwrap();
        let got = files_of(&snap);
        assert_eq!(got.len(), 1);
        assert_eq!(got[0].path, "ref.txt");
        assert_eq!(
            got[0].local_path.as_deref(),
            Some(file.canonicalize().unwrap().as_path())
        );
        assert!(!snap.items.iter().any(|i| matches!(i, ClipData::Png(_))));
    }

