//! Explicit native-domain conversion at the shared v1 codec boundary.
use crate::model as domain;
use oink_foundation::content::ClipId;
use oink_foundation::{
    DeviceId,
    clipboard::{ClipPlatform, Sensitivity},
};
use oink_protocol::v1::{
    self, ErrorCode, RawMap, RawValue as V, dto as wire,
    schema::{Open, WireDto, WireValue},
};

fn invalid() -> v1::Error {
    ErrorCode::UnsupportedValue.into()
}
fn map<const N: usize>(fields: [(u32, V); N]) -> RawMap {
    fields.into()
}
fn body(kind: u64, fields: RawMap) -> RawMap {
    map([(1, V::Uint(kind)), (2, V::Map(fields))])
}
fn optional<T: WireValue>(value: Option<T>) -> V {
    value.write()
}
fn text(value: impl Into<String>) -> V {
    V::Text(value.into())
}
fn number(value: impl Into<u64>) -> V {
    V::Uint(value.into())
}

pub fn device(value: DeviceId) -> wire::DeviceId {
    wire::DeviceId::from_raw(map([(1, text("ed25519")), (2, V::Bytes(value.0.to_vec()))]))
        .expect("local Ed25519 identity")
}
fn local_device(value: wire::DeviceId) -> v1::Result<DeviceId> {
    value.require_supported()?;
    Ok(DeviceId(value.public_key()?.0.try_into().map_err(|_| invalid())?))
}
pub fn digest(bytes: [u8; 32]) -> wire::Digest {
    wire::Digest::from_raw(map([(1, text("blake3-256")), (2, V::Bytes(bytes.to_vec()))])).expect("local BLAKE3 digest")
}
pub fn local_digest(value: wire::Digest) -> v1::Result<[u8; 32]> {
    if value.algorithm()?.0 != "blake3-256" {
        return Err(invalid());
    }
    value.bytes()?.0.try_into().map_err(|_| invalid())
}
pub fn clip_id(value: ClipId) -> wire::ClipId {
    wire::ClipId::from_raw(map([(1, device(value.origin).write()), (2, number(value.seq))]))
        .expect("local clipboard identity")
}
pub fn local_clip_id(value: wire::ClipId) -> v1::Result<ClipId> {
    Ok(ClipId {
        origin: local_device(value.origin()?)?,
        seq: value.seq()?,
    })
}
pub fn offer_id(value: domain::OfferId) -> wire::OfferId {
    wire::OfferId::from_raw(map([(1, clip_id(value.clip).write()), (2, number(value.generation))]))
        .expect("local offer identity")
}
pub fn local_offer_id(value: wire::OfferId) -> v1::Result<domain::OfferId> {
    Ok(domain::OfferId {
        clip: local_clip_id(value.clip()?)?,
        generation: value.generation()?,
    })
}
pub fn delivery_id(value: domain::DeliveryId) -> wire::DeliveryId {
    wire::DeliveryId::from_raw(map([
        (1, offer_id(value.offer).write()),
        (2, device(value.receiver).write()),
        (3, number(value.sequence)),
    ]))
    .expect("local delivery identity")
}
pub fn local_delivery_id(value: wire::DeliveryId) -> v1::Result<domain::DeliveryId> {
    Ok(domain::DeliveryId {
        offer: local_offer_id(value.offer()?)?,
        receiver: local_device(value.receiver()?)?,
        sequence: value.sequence()?,
    })
}
pub fn platform(value: ClipPlatform) -> &'static str {
    match value {
        ClipPlatform::Mac => "macos",
        ClipPlatform::Windows => "windows",
        ClipPlatform::Unknown => "unknown",
    }
}
fn local_platform(value: &str) -> v1::Result<ClipPlatform> {
    match value {
        "macos" => Ok(ClipPlatform::Mac),
        "windows" => Ok(ClipPlatform::Windows),
        _ => Ok(ClipPlatform::Unknown),
    }
}
pub fn sensitivity(value: Sensitivity) -> wire::Sensitivity {
    match value {
        Sensitivity::Normal => wire::Sensitivity::Normal,
        Sensitivity::Concealed => wire::Sensitivity::Concealed,
        Sensitivity::Transient => wire::Sensitivity::Transient,
        Sensitivity::AutoGenerated => wire::Sensitivity::AutoGenerated,
    }
}
pub fn local_sensitivity(value: wire::Sensitivity) -> v1::Result<Sensitivity> {
    match value {
        wire::Sensitivity::Normal => Ok(Sensitivity::Normal),
        wire::Sensitivity::Concealed => Ok(Sensitivity::Concealed),
        wire::Sensitivity::Transient => Ok(Sensitivity::Transient),
        wire::Sensitivity::AutoGenerated => Ok(Sensitivity::AutoGenerated),
        _ => Err(invalid()),
    }
}

pub fn format(value: &domain::NativeFormat) -> wire::FormatId {
    wire::FormatId(match value {
        domain::NativeFormat::Mac(name) => format!("mac-uti:{name}"),
        domain::NativeFormat::WindowsRegistered(name) => format!("win-name:{name}"),
        domain::NativeFormat::WindowsPredefined(id) => format!("win-cf:{id}"),
        domain::NativeFormat::Unknown(name) => name.clone(),
    })
}
fn local_format(value: wire::FormatId) -> v1::Result<domain::NativeFormat> {
    let (namespace, name) = value.0.split_once(':').ok_or_else(invalid)?;
    Ok(match namespace {
        "mac-uti" => domain::NativeFormat::Mac(name.into()),
        "win-name" => domain::NativeFormat::WindowsRegistered(name.into()),
        "win-cf" => match name
            .parse::<u16>()
            .ok()
            .filter(|id| (1..=17).contains(id) && id.to_string() == name)
        {
            Some(id) => domain::NativeFormat::WindowsPredefined(id),
            None => domain::NativeFormat::Unknown(value.0),
        },
        _ => domain::NativeFormat::Unknown(value.0),
    })
}

pub fn portable(value: domain::StandardFormat) -> wire::FormatId {
    wire::FormatId(
        match value {
            domain::StandardFormat::Text => crate::negotiation::PORTABLE_FORMATS[0],
            domain::StandardFormat::Html => crate::negotiation::PORTABLE_FORMATS[1],
            domain::StandardFormat::Rtf => crate::negotiation::PORTABLE_FORMATS[2],
            domain::StandardFormat::Png => crate::negotiation::PORTABLE_FORMATS[3],
            domain::StandardFormat::Privacy => crate::negotiation::PORTABLE_FORMATS[5],
            domain::StandardFormat::Url => crate::negotiation::PORTABLE_FORMATS[6],
        }
        .into(),
    )
}
fn local_portable(value: &wire::FormatId) -> Option<domain::StandardFormat> {
    [
        domain::StandardFormat::Text,
        domain::StandardFormat::Html,
        domain::StandardFormat::Rtf,
        domain::StandardFormat::Png,
        domain::StandardFormat::Privacy,
        domain::StandardFormat::Url,
    ]
    .into_iter()
    .find(|standard| portable(*standard) == *value)
}
fn medium(value: domain::Medium) -> wire::Medium {
    match value {
        domain::Medium::Bytes => wire::Medium::Bytes,
        domain::Medium::HGlobal => wire::Medium::HGlobal,
        domain::Medium::Stream => wire::Medium::Stream,
        domain::Medium::Storage => wire::Medium::Storage,
        domain::Medium::Bitmap => wire::Medium::Bitmap,
        domain::Medium::Palette => wire::Medium::Palette,
        domain::Medium::Metafile => wire::Medium::Metafile,
        domain::Medium::EnhancedMetafile => wire::Medium::EnhancedMetafile,
        domain::Medium::File => wire::Medium::File,
    }
}
fn local_medium(value: wire::Medium) -> v1::Result<domain::Medium> {
    match value {
        wire::Medium::Bytes => Ok(domain::Medium::Bytes),
        wire::Medium::HGlobal => Ok(domain::Medium::HGlobal),
        wire::Medium::Stream => Ok(domain::Medium::Stream),
        wire::Medium::Storage => Ok(domain::Medium::Storage),
        wire::Medium::Bitmap => Ok(domain::Medium::Bitmap),
        wire::Medium::Palette => Ok(domain::Medium::Palette),
        wire::Medium::Metafile => Ok(domain::Medium::Metafile),
        wire::Medium::EnhancedMetafile => Ok(domain::Medium::EnhancedMetafile),
        wire::Medium::File => Ok(domain::Medium::File),
        _ => Err(invalid()),
    }
}
pub fn unavailable(value: domain::Unavailable) -> wire::ContentUnavailable {
    wire::ContentUnavailable::from_number(match value {
        domain::Unavailable::Unsupported => 0,
        domain::Unavailable::LimitExceeded => 1,
        domain::Unavailable::Superseded => 2,
        domain::Unavailable::ReadFailed => 3,
        domain::Unavailable::Cancelled => 4,
        domain::Unavailable::NoSuchItem => 5,
        domain::Unavailable::Permission => 6,
        domain::Unavailable::NoProgress => 7,
        domain::Unavailable::StorageFull => 8,
        domain::Unavailable::InvalidData => 9,
    })
}
pub fn local_unavailable(value: wire::ContentUnavailable) -> domain::Unavailable {
    match value.number() {
        0 => domain::Unavailable::Unsupported,
        1 => domain::Unavailable::LimitExceeded,
        2 => domain::Unavailable::Superseded,
        3 => domain::Unavailable::ReadFailed,
        4 => domain::Unavailable::Cancelled,
        5 => domain::Unavailable::NoSuchItem,
        6 => domain::Unavailable::Permission,
        7 => domain::Unavailable::NoProgress,
        8 => domain::Unavailable::StorageFull,
        9 => domain::Unavailable::InvalidData,
        _ => domain::Unavailable::Unsupported,
    }
}
fn size(value: domain::ContentSize) -> v1::Result<wire::ContentSize> {
    wire::ContentSize::from_raw(match value {
        domain::ContentSize::Unknown => body(0, RawMap::new()),
        domain::ContentSize::Known(bytes) => body(1, map([(1, number(bytes))])),
    })
}
fn local_size(value: wire::ContentSize) -> v1::Result<domain::ContentSize> {
    match value.variant()? {
        Open::Known(wire::ContentSizeKind::UnknownSize) => Ok(domain::ContentSize::Unknown),
        Open::Known(wire::ContentSizeKind::Known) => Ok(domain::ContentSize::Known(
            wire::KnownSize::from_raw(value.body()?)?.bytes()?,
        )),
        _ => Err(invalid()),
    }
}
fn representation_data(value: &domain::RepresentationData) -> v1::Result<wire::RepresentationData> {
    wire::RepresentationData::from_raw(match value {
        domain::RepresentationData::Reader { size: value, hash } => {
            body(0, map([(1, size(*value)?.write()), (2, optional(hash.map(digest)))]))
        }
        domain::RepresentationData::Inline(bytes) => body(1, map([(1, V::Bytes(bytes.clone()))])),
        domain::RepresentationData::File(node) => body(2, map([(1, number(node.0))])),
        domain::RepresentationData::Unavailable(reason) => body(3, map([(1, unavailable(*reason).write())])),
        domain::RepresentationData::Promise(node, bytes) => {
            body(4, map([(1, number(node.0)), (2, V::Bytes(bytes.clone()))]))
        }
    })
}
fn local_representation_data(value: wire::RepresentationData) -> v1::Result<domain::RepresentationData> {
    Ok(match value.variant()? {
        Open::Known(wire::RepresentationDataKind::Reader) => {
            let value = wire::RepresentationReader::from_raw(value.body()?)?;
            domain::RepresentationData::Reader {
                size: local_size(value.size()?)?,
                hash: value.hash()?.map(local_digest).transpose()?,
            }
        }
        Open::Known(wire::RepresentationDataKind::Inline) => {
            domain::RepresentationData::Inline(wire::RepresentationInline::from_raw(value.body()?)?.bytes()?.0)
        }
        Open::Known(wire::RepresentationDataKind::File) => domain::RepresentationData::File(domain::NodeId(
            wire::RepresentationFile::from_raw(value.body()?)?.node()?,
        )),
        Open::Known(wire::RepresentationDataKind::Unavailable) => domain::RepresentationData::Unavailable(
            local_unavailable(wire::RepresentationUnavailable::from_raw(value.body()?)?.reason()?),
        ),
        Open::Known(wire::RepresentationDataKind::Promise) => {
            let value = wire::RepresentationPromise::from_raw(value.body()?)?;
            domain::RepresentationData::Promise(domain::NodeId(value.node()?), value.bytes()?.0)
        }
        _ => domain::RepresentationData::Unavailable(domain::Unavailable::Unsupported),
    })
}
fn representation(value: &domain::Representation) -> v1::Result<wire::Representation> {
    wire::Representation::from_raw(map([
        (1, number(value.id.0)),
        (2, format(&value.format).write()),
        (3, medium(value.medium).write()),
        (4, number(value.aspect)),
        (5, value.index.write()),
        (6, optional(value.standard.map(portable))),
        (7, representation_data(&value.data)?.write()),
    ]))
}
fn local_representation(value: wire::Representation) -> v1::Result<domain::Representation> {
    let native = local_format(value.format()?)?;
    let medium = local_medium(value.medium()?);
    let data = if medium.is_err() {
        domain::RepresentationData::Unavailable(domain::Unavailable::Unsupported)
    } else {
        local_representation_data(value.data()?)?
    };
    Ok(domain::Representation {
        id: domain::RepresentationId(value.id()?),
        format: native,
        medium: medium.unwrap_or(domain::Medium::Bytes),
        aspect: value.aspect()?,
        index: value.index()?,
        standard: value.portable_format()?.as_ref().and_then(local_portable),
        data,
    })
}
pub fn node(value: &domain::FileNode) -> v1::Result<wire::FileNode> {
    wire::FileNode::from_raw(map([
        (1, number(value.id.0)),
        (2, optional(value.parent.map(|node| node.0))),
        (3, text(&value.name)),
        (
            4,
            match value.kind {
                domain::NodeKind::File => wire::NodeKind::File,
                domain::NodeKind::Directory => wire::NodeKind::Directory,
            }
            .write(),
        ),
        (5, size(value.size)?.write()),
        (6, number(value.version)),
        (7, optional(value.modified_ms)),
    ]))
}
pub fn local_node(value: wire::FileNode) -> v1::Result<domain::FileNode> {
    Ok(domain::FileNode {
        id: domain::NodeId(value.id()?),
        parent: value.parent()?.map(domain::NodeId),
        name: value.name()?.0,
        kind: match value.kind()? {
            wire::NodeKind::File => domain::NodeKind::File,
            wire::NodeKind::Directory => domain::NodeKind::Directory,
            _ => return Err(invalid()),
        },
        size: local_size(value.size()?)?,
        version: value.version()?,
        modified_ms: value.modified_ms()?,
    })
}
pub fn inventory(value: &domain::Inventory) -> v1::Result<wire::Inventory> {
    let items = value
        .items
        .iter()
        .map(|item| {
            wire::ContentItem::from_raw(map([
                (1, number(item.id.0)),
                (2, optional(item.file.map(|node| node.0))),
                (4, V::Bool(item.virtual_files)),
                (
                    3,
                    V::Array(
                        item.representations
                            .iter()
                            .map(|rep| representation(rep).map(|rep| rep.write()))
                            .collect::<v1::Result<_>>()?,
                    ),
                ),
            ]))
        })
        .map(|item| item.map(|item| item.write()))
        .collect::<v1::Result<_>>()?;
    wire::Inventory::from_raw(map([
        (1, offer_id(value.id).write()),
        (2, text(platform(value.platform))),
        (3, V::Array(items)),
        (
            4,
            V::Array(
                value
                    .roots
                    .iter()
                    .map(|root| node(root).map(|root| root.write()))
                    .collect::<v1::Result<_>>()?,
            ),
        ),
    ]))
}

/// A descriptor remainder carries no inline payload. The source keeps the
/// original bytes and serves the same stable representation through Reader.
pub fn descriptor_inventory(original: &wire::Inventory) -> v1::Result<wire::Inventory> {
    let mut raw = original.raw().clone();
    let mut items = Vec::new();
    for item in original.items()?.0 {
        let mut item_raw = item.raw().clone();
        let mut representations = Vec::new();
        for representation in item.representations()?.0 {
            let mut representation_raw = representation.raw().clone();
            let data = representation.data()?;
            if data.variant()? == Open::Known(wire::RepresentationDataKind::Inline) {
                let bytes = wire::RepresentationInline::from_raw(data.body()?)?.bytes()?.0;
                representation_raw.insert(
                    7,
                    representation_data(&domain::RepresentationData::Reader {
                        size: domain::ContentSize::Known(bytes.len() as u64),
                        hash: Some(blake3::hash(&bytes).into()),
                    })?
                    .write(),
                );
            }
            representations.push(V::Map(representation_raw));
        }
        item_raw.insert(3, V::Array(representations));
        items.push(V::Map(item_raw));
    }
    raw.insert(3, V::Array(items));
    wire::Inventory::from_raw(raw)
}

pub fn reliable_inventory(original: &wire::Inventory) -> v1::Result<wire::Inventory> {
    if original.inline_bytes()? > v1::limits::RELIABLE_INLINE {
        descriptor_inventory(original)
    } else {
        Ok(original.clone())
    }
}

/// Update delivery outcomes in the retained tree without rebuilding descriptors
/// from their supported native view. Unknown fields remain byte-preservable.
pub fn updated_inventory(original: &wire::Inventory, local: &domain::Inventory) -> v1::Result<wire::Inventory> {
    let mut raw = original.raw().clone();
    let mut items = Vec::new();
    for item in original.items()?.0 {
        let mut item_raw = item.raw().clone();
        let mut representations = Vec::new();
        for representation in item.representations()?.0 {
            let mut representation_raw = representation.raw().clone();
            if let Some(local) = crate::content::find(local, domain::RepresentationId(representation.id()?))
                && let domain::RepresentationData::Unavailable(reason) = local.data
                && local_representation(representation.clone())?.data != local.data
            {
                representation_raw.insert(
                    7,
                    representation_data(&domain::RepresentationData::Unavailable(reason))?.write(),
                );
            }
            representations.push(V::Map(representation_raw));
        }
        item_raw.insert(3, V::Array(representations));
        items.push(V::Map(item_raw));
    }
    raw.insert(3, V::Array(items));
    wire::Inventory::from_raw(raw)
}
pub fn local_inventory(value: &wire::Inventory) -> v1::Result<domain::Inventory> {
    let items = value
        .items()?
        .0
        .into_iter()
        .map(|item| {
            Ok(domain::ContentItem {
                virtual_files: item.virtual_files()?,
                id: domain::ItemId(item.id()?),
                file: item.file()?.map(domain::NodeId),
                representations: item
                    .representations()?
                    .0
                    .into_iter()
                    .map(local_representation)
                    .collect::<v1::Result<_>>()?,
            })
        })
        .collect::<v1::Result<_>>()?;
    Ok(domain::Inventory {
        id: local_offer_id(value.id()?)?,
        platform: local_platform(&value.platform()?.0)?,
        items,
        roots: value
            .roots()?
            .0
            .into_iter()
            .map(local_node)
            .collect::<v1::Result<_>>()?,
    })
}
