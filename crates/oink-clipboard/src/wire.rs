pub(crate) fn nodes_size(nodes: &[domain::FileNode]) -> v1::Result<usize> {
    nodes.iter().try_fold(64usize, |size, value| {
        size.checked_add(node(value)?.encode(v1::limits::LOW_FRAME)?.len())
            .ok_or_else(|| v1::ErrorCode::LimitExceeded.into())
    })
}
