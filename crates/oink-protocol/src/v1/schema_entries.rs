// Add carrying DTO / unit enum names once here. IDs/keys remain explicit in
// their declarations; this list controls only introspection and conformance.
macro_rules! dto_schemas {
    ($($name:ident),* $(,)?)=>{
        pub const SCHEMAS:&[Schema]=&[$($name::SCHEMA,)*];
        pub fn preflight_schema(name:&str,d:&mut minicbor::Decoder<'_>,depth:usize)->Result<()> {
            match name {$(stringify!($name)=><$name as WireDto>::preflight(d,depth),)* _=>Err(ErrorCode::UnsupportedValue.into())}
        }
        pub fn validate_schema(name:&str,raw:&RawMap)->Result<()> {
            match name {$(stringify!($name)=>{$name::validate_raw(raw)?;},)* _=>return Err(ErrorCode::UnsupportedValue.into())}
            Ok(())
        }
    };
}
macro_rules! enum_schemas {
    ($($name:ident),* $(,)?)=>{
        pub const ENUMS:&[(&str,&[(u32,&str)])]=&[$((stringify!($name),$name::VALUES),)*];
        pub fn validate_enum(name:&str,value:&super::RawValue)->Result<()> {
            use super::schema::WireValue;
            match name {$(stringify!($name)=>{$name::read(value)?;},)* _=>return Err(ErrorCode::UnsupportedValue.into())}
            Ok(())
        }
    };
}
