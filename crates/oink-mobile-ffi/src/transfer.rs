use crate::MobileCoreError;
use oink_mobile_core::{Peer, PeerKind, PeerState, SendItem, SendOrigin};

#[derive(Clone, Debug, uniffi::Record)]
pub struct MobilePeer {
    pub id: String,
    pub kind: String,
    pub state: String,
    pub accepts_clipboard: bool,
    pub connection_order: u64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum MobileShareSensitivity {
    Normal,
    Concealed,
    Transient,
    AutoGenerated,
}
impl From<MobileShareSensitivity> for oink_foundation::clipboard::Sensitivity {
    fn from(value: MobileShareSensitivity) -> Self {
        match value {
            MobileShareSensitivity::Normal => Self::Normal,
            MobileShareSensitivity::Concealed => Self::Concealed,
            MobileShareSensitivity::Transient => Self::Transient,
            MobileShareSensitivity::AutoGenerated => Self::AutoGenerated,
        }
    }
}

#[derive(Clone, Debug, uniffi::Enum)]
pub enum MobileShareItem {
    /// Text with every rich format the phone has for it (2026-11-12: phones
    /// send all formats): `html` (Android `ClipData.Item.htmlText`, iOS
    /// `public.html`) and `rtf` (iOS `public.rtf`, RTFD flattened to RTF).
    /// It travels as one item with a representation per format; PCs put
    /// them all on their clipboard.
    Text {
        text: String,
        #[uniffi(default = None)]
        html: Option<String>,
        #[uniffi(default = None)]
        rtf: Option<String>,
    },
    /// `staged`: the host's own staged copy (share extension / share intent
    /// staging, a photo the page wrote), in the same container or volume as
    /// the session's data directory. The core moves it into its attachment
    /// store; after a successful call the host must not delete it. Without
    /// it (a document-picker file) the core copies the file. When the call
    /// fails, nothing was taken that the host still has to keep: it cleans
    /// its staging as before.
    ///
    /// `width`/`height`: the original's pixel size as it is displayed
    /// (EXIF / HEIF orientation applied), read by the host's own decoder
    /// (iOS `CGImageSource` properties, Android bounds decode + orientation).
    /// The own message keeps it so both apps show the image at its ratio.
    /// Give both or neither; both must be positive.
    Image {
        path: String,
        encoded_size: u64,
        mime: String,
        staged: bool,
        #[uniffi(default = None)]
        width: Option<u32>,
        #[uniffi(default = None)]
        height: Option<u32>,
    },
    File {
        path: String,
        name: String,
        size: u64,
        mime: Option<String>,
        staged: bool,
    },
    Folder {
        path: String,
        name: String,
    },
}

pub(crate) fn peer(value: MobilePeer) -> Result<Peer, MobileCoreError> {
    Ok(Peer {
        id: value.id,
        kind: match value.kind.as_str() {
            "pc" => PeerKind::Pc,
            "mobile" => PeerKind::Mobile,
            _ => {
                return Err(MobileCoreError::InvalidArgument {
                    detail: "unknown peer kind".into(),
                });
            }
        },
        state: match value.state.as_str() {
            "ready" => PeerState::Ready,
            "offline" => PeerState::Offline,
            "connecting" => PeerState::Connecting,
            _ => {
                return Err(MobileCoreError::InvalidArgument {
                    detail: "unknown peer state".into(),
                });
            }
        },
        accepts_clipboard: value.accepts_clipboard,
        connection_order: value.connection_order,
        relayed: false,
        clipboard_pending: false,
    })
}

pub(crate) fn share_item(value: MobileShareItem) -> Result<SendItem, MobileCoreError> {
    Ok(match value {
        MobileShareItem::Text { text, html, rtf } => SendItem::text(
            text,
            html.filter(|html| !html.is_empty()),
            rtf.filter(|rtf| !rtf.is_empty()),
        ),
        MobileShareItem::Image {
            path,
            encoded_size,
            mime,
            staged,
            width,
            height,
        } => SendItem::Image {
            path,
            encoded_size,
            mime,
            staged,
            dimensions: match (width, height) {
                (None, None) => None,
                (Some(width), Some(height)) if width > 0 && height > 0 => Some((width, height)),
                _ => {
                    return Err(MobileCoreError::InvalidArgument {
                        detail: "an image's width and height go together and are positive".into(),
                    });
                }
            },
        },
        MobileShareItem::File {
            path,
            name,
            size,
            mime,
            staged,
        } => SendItem::File {
            path,
            name,
            size,
            mime,
            staged,
        },
        MobileShareItem::Folder { path, name } => SendItem::Folder { path, name },
    })
}

pub(crate) fn send_origin(value: &str) -> Result<SendOrigin, MobileCoreError> {
    match value {
        "transfer" => Ok(SendOrigin::TransferPage),
        "ios-share" => Ok(SendOrigin::IosShare),
        "android-share" => Ok(SendOrigin::AndroidShare),
        "android-open-with" => Ok(SendOrigin::AndroidOpenWith),
        _ => Err(MobileCoreError::InvalidArgument {
            detail: "unknown share origin".into(),
        }),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn image(width: Option<u32>, height: Option<u32>) -> MobileShareItem {
        MobileShareItem::Image {
            path: "/photo.heic".into(),
            encoded_size: 0,
            mime: "image/heic".into(),
            staged: true,
            width,
            height,
        }
    }

    /// The host's displayed original size reaches the core as one pair;
    /// half a size or a zero edge is refused instead of guessed.
    #[test]
    fn an_image_carries_its_original_size_as_a_pair() {
        let dimensions = |item| match share_item(item) {
            Ok(SendItem::Image { dimensions, .. }) => Ok(dimensions),
            Ok(other) => panic!("not an image: {other:?}"),
            Err(error) => Err(error),
        };
        assert_eq!(dimensions(image(Some(3024), Some(4032))).unwrap(), Some((3024, 4032)));
        assert_eq!(dimensions(image(None, None)).unwrap(), None);
        for (width, height) in [
            (Some(3024), None),
            (None, Some(4032)),
            (Some(0), Some(4032)),
            (Some(3024), Some(0)),
        ] {
            assert!(matches!(
                dimensions(image(width, height)),
                Err(MobileCoreError::InvalidArgument { .. })
            ));
        }
    }
}
