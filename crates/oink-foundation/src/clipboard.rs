//! 剪贴板内容模型（平台实现读写系统剪贴板时使用；同步逻辑在 `oink-clipboard::sync`）。
//!
//! Clipboard metadata is shared separately from file contents fetched on demand.

use serde::{Deserialize, Serialize};

/// 一种表示形式。同一次复制通常同时带有多种形式（如 HTML + 纯文本）。
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum ClipData {
    Text(String),
    /// HTML 片段（不含 Windows `CF_HTML` 的头部偏移信息，由平台实现转换）。
    Html(String),
    Rtf(Vec<u8>),
    /// 图片统一用 PNG 传输。
    Png(Vec<u8>),
    /// 文件与文件夹（M4）：只描述，内容按需拉取。
    Files(Vec<FileEntry>),
    /// 平台私有的字节格式；接收端仅写同平台格式，或经显式映射转换。
    Custom {
        platform: ClipPlatform,
        name: String,
        bytes: Vec<u8>,
    },
    /// One native item with ordered representation metadata. Bytes are read through
    /// the content provider bound to the enclosing clipboard/drag offer.
    Native {
        platform: ClipPlatform,
        item: crate::content::ContentItem,
    },
    /// Only selected roots. Children are fetched from the offer namespace on demand.
    FileRoots(#[serde(deserialize_with = "crate::content::bounded::vec::<_, _, 65535>")] Vec<crate::content::FileNode>),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ClipPlatform {
    Mac,
    Windows,
    /// An open wire platform without a native reconstruction contract here.
    Unknown,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct FileEntry {
    /// 相对于本次复制根的路径，使用 `/` 分隔。顶层条目就是被复制的文件或文件夹本身的名字；
    /// 文件夹展开后，其中的每个文件和子文件夹各占一条（父目录在前）。
    pub path: String,
    pub is_dir: bool,
    pub size: u64,
    /// 修改时间，Unix 毫秒。
    pub modified_ms: Option<i64>,
    /// 本机上的绝对路径（M4）：
    /// - 源端 `read()` 读到被复制的文件时填写，供同步逻辑读取内容发给对端；
    /// - 接收端文件已下载到本地后填写，交给 `write()` 写成系统的文件列表（macOS `public.file-url`、Windows `CF_HDROP`）。
    ///
    /// 只在本机使用，不随消息发送。
    #[serde(skip)]
    pub local_path: Option<std::path::PathBuf>,
}

/// 内容的隐私级别（与剪贴板管理器共存）。
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Sensitivity {
    Normal,
    /// 密码等：同步并透传原始标记（实际历史行为由目标应用决定）。
    Concealed,
    /// 临时内容：同步并透传标记。
    Transient,
    /// 程序自动生成、非用户主动复制的内容（nspasteboard.org `org.nspasteboard.AutoGeneratedType`）：
    /// 照常同步；写入 macOS 时带上该标记，剪贴板管理器可以选择不收录。Windows 没有对应标记，按 `Normal` 写入。
    /// 同时带有多个标记时此摘要取更严格的那个，精确标记由 Custom 表示形式保留。
    AutoGenerated,
}

/// 读取到的一次剪贴板内容。
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ClipSnapshot {
    pub items: Vec<ClipData>,
    pub sensitivity: Sensitivity,
    /// 系统剪贴板的变化计数（macOS `changeCount`；Windows `GetClipboardSequenceNumber`）。
    pub change_count: u64,
}
