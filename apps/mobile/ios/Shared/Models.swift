    static func toolbarMicrophone(on: Bool, failed: Bool) -> MicMode? {
        failed ? .unavailable : on ? .send : nil
    }
}


/// System share routing; one other member skips the picker even while offline.
func automaticShareTarget(_ targets: SendTargets, bytes: UInt64?) -> SendTarget? {
    if targets.otherDevices == 1 { return targets.onlyDevice }
    guard let bytes, bytes < 300_000_000 else { return nil }
    return targets.online.first { $0.id == targets.activeDevice && $0.isComputer }
        ?? targets.online.first { $0.isComputer }
}
