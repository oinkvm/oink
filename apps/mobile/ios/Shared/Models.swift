/// The state projection is shared with Android through contracts/share-animation.md.
/// The core owns transfer events; this value only drives the card presentation.
struct ShareUiState: Equatable {
    enum Phase: String, Equatable {
        case preparing = "PREPARING"
        /// The group's only other device is offline: the core holds the share back,
        /// nothing is recorded or sent, and it starts by itself once that device is
        /// online (user 2026-11-11).
        case waiting = "WAITING"
        case sending = "SENDING"
        case failed = "FAILED"
        case succeeded = "SUCCEEDED"
    }

    var phase: Phase
    var statusText: String
    var progress: Double?
    /// Sending straight to a phone (the stage ends on a phone, the card asks to stay open).
    var toPhone = false

    /// The waiting card's text (no trailing period, user 2026-11-11).
    static var waitingText: String {
        // Chinese breaks after「Oink」on purpose (share-anim SPEC §2.1).
        AppText.pick("对方不在线，请在对方设备打开 Oink\n并确保网络连接畅通",
                     "The other device is offline. Open Oink on it and make sure it's connected to the network")
    }

    /// The core said whether the share in flight waits for its offline target
    /// (`CoreSession.sharesWaitingForTarget`): the waiting card, and back to the
    /// progress card (`sendingText`, progress unknown yet) once it starts. Other
    /// phases (preparing, finished) are left alone.
    func targetWaiting(_ waiting: Bool, sendingText: String) -> ShareUiState {
        switch (phase, waiting) {
        case (.sending, true), (.waiting, true):
            return ShareUiState(phase: .waiting, statusText: Self.waitingText, progress: nil, toPhone: toPhone)
        case (.waiting, false):
            return ShareUiState(phase: .sending, statusText: sendingText, progress: nil, toPhone: toPhone)
        default:
            return self
        }
    }
}

enum ShareStatusFormatter {
    static func rate(bytesPerSecond: Double) -> String {
        let safe = max(0, bytesPerSecond)
        var unit = 0
        var value = safe / pow(1000, Double(unit + 1))
        while unit < 2 && value >= 1000 {
            unit += 1
            value = safe / pow(1000, Double(unit + 1))
        }
        var text = significant(value)
        if value >= 0 && (Double(text) ?? 0) >= 1000, unit < 2 {
            unit += 1
            value = safe / pow(1000, Double(unit + 1))
            text = significant(value)
        }
        return "\(text) \(["KB/s", "MB/s", "GB/s"][unit])"
    }

    static func elapsed(seconds: Double) -> String { significant(max(0, seconds)) }

    private static func significant(_ value: Double) -> String {
        guard value != 0 else { return "0" }
        var exponent = Int(floor(log10(abs(value))))
        var decimals = max(0, 2 - exponent)
        var rounded = (value * pow(10, Double(decimals))).rounded() / pow(10, Double(decimals))
        let roundedExponent = Int(floor(log10(abs(rounded))))
        if roundedExponent != exponent {
            exponent = roundedExponent
            decimals = max(0, 2 - exponent)
            rounded = (value * pow(10, Double(decimals))).rounded() / pow(10, Double(decimals))
        }
        return String(format: "%.*f", decimals, rounded)
    }
}

