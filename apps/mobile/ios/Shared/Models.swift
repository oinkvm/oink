/// Text in the app language: Chinese when the preferred language is Chinese,
/// English otherwise (mockup rule). 设置 › 语言 sets AppleLanguages, which
/// this follows from the next launch.
enum AppText {
    /// Temporary: always Chinese until the language setting exists (it will replace this
    /// and choose by its setting). Choosing by the system language mixed the languages on
    /// a phone set to English: AppText strings came out in English beside the Chinese
    /// literals (user 2026-11-11). Callers keep passing the English text for that setting.
    /// The string catalogs hold only zh-Hans for the same reason: with an `en` localization
    /// in the bundle iOS ran the app in English on such a phone, so the system's own texts
    /// inside Oink (edit menus, pickers, Shortcuts tips, App Intents) were English too.
    static func pick(_ zh: String, _ en: String) -> String { zh }
}

/// Space display: KB below 1 MB, MB below 1 GB, then GB; 2 decimals below 10, 1 below 100.
func formatBytes(_ n: Int64) -> String {
    if n <= 0 { return "0 KB" }
    let units = ["KB", "MB", "GB"]
    var v = Double(n) / 1024, i = 0
    while v >= 1024 && i < units.count - 1 { v /= 1024; i += 1 }
    let text = v >= 100 || i == 0 ? String(Int(v.rounded())) : String(format: v >= 10 ? "%.1f" : "%.2f", v)
    return "\(text) \(units[i])"
}

